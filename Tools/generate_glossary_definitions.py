def list_literal(values: list[str]) -> str:
    inner = ", ".join(f'"{esc(v)}"' for v in values)
    return f"new List<string> {{ {inner} }}"


def emit_term(t: dict) -> str:
    props: list[str] = [
        f'Id = "{esc(t["id"])}"',
        f'Term = "{esc(t["name"])}"',
    ]
    if t["abbr"]:
        props.append(f'Abbreviation = "{esc(t["abbr"])}"')
    props.extend(
        [
            f'Category = {CAT[t["cat"]]}',
            f'Difficulty = {DIFF[t["diff"]]}',
            f'ShortDefinition = "{esc(t["short"])}"',
            f'SimpleExplanation = "{esc(t["simple"])}"',
            f'WhyItMatters = "{esc(t["why"])}"',
            f'Example = "{esc(t["example"])}"',
            f'CommonMistake = "{esc(t["mistake"])}"',
            f'PracticePrompt = "{esc(t["practice"])}"',
            f"GameUses = {list_literal(t['uses'])}",
            f"Tags = {list_literal(t['tags'])}",
        ]
    )
    if t["synonyms"]:
        props.append(f"Synonyms = {list_literal(t['synonyms'])}")
    props.append(f"RelatedTermIds = {list_literal(t['related'])}")
    if t["code"]:
        props.append(f'CodeExample = "{esc(t["code"])}"')
    if t["diagram"]:
        props.append("HasDiagram = true")
        props.append(f"DiagramType = {DIAG[t['diagram']]}")

    indented = ",\n".join("                " + p for p in props)
    return (
        "            Add(new GlossaryTermData\n"
        "            {\n"
        f"{indented}\n"
        "            });"
    )


