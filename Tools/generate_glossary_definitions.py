def generate_csharp(terms: list[dict]) -> str:
    chunks = [
        "using System;",
        "using System.Collections.Generic;",
        "",
        "namespace GameTerms.Editor",
        "{",
        "    public static class GlossaryContentDefinitions",
        "    {",
        "        public static IReadOnlyList<GlossaryTermData> CreateAllTerms()",
        "        {",
        "            var baseDate = new DateTimeOffset(2024, 1, 1, 0, 0, 0, TimeSpan.Zero).ToUnixTimeSeconds();",
        "            var terms = new List<GlossaryTermData>();",
        "            var index = 0;",
        "",
        "            void Add(GlossaryTermData term)",
        "            {",
        "                term.AddedAtUnix = baseDate + index * 86400L;",
        "                terms.Add(term);",
        "                index++;",
        "            }",
        "",
    ]

    by_cat: dict[str, list[dict]] = {c: [] for c in CATEGORY_ORDER}
    for t in terms:
        by_cat[t["cat"]].append(t)

    for cat in CATEGORY_ORDER:
        chunks.append(f"            // {CATEGORY_HEADERS[cat]}")
        for t in by_cat[cat]:
            chunks.append(emit_term(t))
            chunks.append("")
        chunks.append("")

    chunks.extend(
        [
            "            return terms;",
            "        }",
            "    }",
            "}",
            "",
        ]
    )
    return "\n".join(chunks)


def validate(terms: list[dict]) -> list[str]:
    issues: list[str] = []
    if len(terms) != 150:
        issues.append(f"Expected 150 terms, got {len(terms)}")

    ids = [t["id"] for t in terms]
    if len(ids) != len(set(ids)):
        from collections import Counter

        dupes = [i for i, n in Counter(ids).items() if n > 1]
        issues.append(f"Duplicate ids: {dupes}")

    id_set = set(ids)
    counts: dict[str, int] = {}
    for t in terms:
        counts[t["cat"]] = counts.get(t["cat"], 0) + 1
        if len(t["uses"]) != 3:
            issues.append(f"{t['id']}: GameUses must have exactly 3")
        if len(t["tags"]) < 1:
            issues.append(f"{t['id']}: Tags must have at least 1")
        if not (1 <= len(t["related"]) <= 4):
            issues.append(f"{t['id']}: RelatedTermIds must have 1-4 entries")
        if not t["mistake"]:
            issues.append(f"{t['id']}: missing CommonMistake")
        if not t["practice"]:
            issues.append(f"{t['id']}: missing PracticePrompt")
        for rid in t["related"]:
            if rid not in id_set:
                issues.append(f"{t['id']}: related id missing: {rid}")
        if t["diagram"] and t["diagram"] not in DIAG:
            issues.append(f"{t['id']}: invalid diagram {t['diagram']}")

    for cat, n in counts.items():
        if n != 15:
            issues.append(f"Category {cat} has {n} terms, expected 15")
    for cat in CATEGORY_ORDER:
        if cat not in counts:
            issues.append(f"Missing category {cat}")

    return issues


def main() -> None:
    issues = validate(TERMS)
    if issues:
        print("Validation failed:")
        for issue in issues:
            print(" -", issue)
        raise SystemExit(1)

    OUT.write_text(generate_csharp(TERMS), encoding="utf-8")
    print(f"Wrote {len(TERMS)} terms to {OUT}")
    for cat in CATEGORY_ORDER:
        n = sum(1 for t in TERMS if t["cat"] == cat)
        print(f"  {cat}: {n}")


if __name__ == "__main__":
    main()
